import AppKit
import SwiftUI
import ImageIO

enum ClipboardPrivacy {
    static let excludedKey = "clipboardExcludedApps"
    static func isMarkedPrivate(_ items: [NSPasteboardItem]) -> Bool {
        let markers = Set(["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
        return items.contains { item in item.types.contains { markers.contains($0.rawValue) } }
    }
    static func excludes(_ appID: String?, from ids: [String]) -> Bool {
        guard let appID = appID else { return false }
        return ids.contains(appID)
    }
    static var blocksActiveApp: Bool {
        excludes(NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
                 from: UserDefaults.standard.stringArray(forKey: excludedKey) ?? [])
    }
}

struct ClipboardEntry: Identifiable {
    let id = UUID()
    let date: Date
    let title: String
    let icon: String
    let items: [[NSPasteboard.PasteboardType: Data]]
    init(title: String, icon: String, items: [[NSPasteboard.PasteboardType: Data]], date: Date = Date()) {
        self.title = title; self.icon = icon; self.items = items; self.date = date
    }
    var fileURLs: [URL] {
        items.compactMap { $0[.fileURL].flatMap { String(data: $0, encoding: .utf8) }.flatMap(URL.init(string:)) }
    }
    var previewText: String {
        items.compactMap { item in
            (item[.string] ?? item[.URL]).flatMap { String(data: $0, encoding: .utf8) }
        }.joined(separator: "\n\n")
    }
    func previewImage() -> NSImage? {
        guard let item = items.first, let data = item[.png] ?? item[.tiff],
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 768,
                kCGImageSourceCreateThumbnailWithTransform: true
              ] as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: .zero)
    }
    var byteCount: Int { items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } } }
}

final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published var paused = false {
        didSet { lastChange = board.changeCount }
    }
    @Published var notice = ""
    private let board: NSPasteboard
    private var lastChange: Int
    private var blockedChange: Int?
    private let shouldExclude: () -> Bool
    private var timer: Timer?
    private let now: () -> Date
    private var wakeObserver: NSObjectProtocol?
    init(board: NSPasteboard = .general, monitoring: Bool = true, now: @escaping () -> Date = Date.init, shouldExclude: @escaping () -> Bool = { ClipboardPrivacy.blocksActiveApp }) {
        self.now = now
        self.shouldExclude = shouldExclude
        self.board = board
        lastChange = board.changeCount
        if monitoring {
            timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in self?.capture() }
            timer?.tolerance = 0.25
            wakeObserver = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in self?.expire() }
        }
    }
    deinit {
        timer?.invalidate()
        if let observer = wakeObserver { NSWorkspace.shared.notificationCenter.removeObserver(observer) }
    }
    func expire() {
        let cutoff = now().addingTimeInterval(-12 * 60 * 60)
        if entries.contains(where: { $0.date <= cutoff }) { entries.removeAll { $0.date <= cutoff } }
    }
    func capture() {
        expire()
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        let source = board.pasteboardItems ?? []
        guard !shouldExclude(), !ClipboardPrivacy.isMarkedPrivate(source) else {
            blockedChange = lastChange
            return
        }
        blockedChange = nil
        guard !paused else { return }
        let allowed: [NSPasteboard.PasteboardType] = [.fileURL, .png, .tiff, .string, .URL]
        var snapshots: [[NSPasteboard.PasteboardType: Data]] = []
        var total = 0
        for item in source {
            var snapshot: [NSPasteboard.PasteboardType: Data] = [:]
            // Preserve file groups and one image representation, rather than all app-private formats.
            let types: [NSPasteboard.PasteboardType]
            if item.types.contains(.fileURL) { types = [.fileURL] }
            else if item.types.contains(.png) { types = [.png] }
            else if item.types.contains(.tiff) { types = [.tiff] }
            else { types = [.string, .URL] }
            for type in allowed where types.contains(type) {
                if let data = item.data(forType: type) {
                    total += data.count
                    guard total <= 10 * 1024 * 1024 else { notice = L("Объект больше 10 МБ — не сохранён", "Item exceeds 10 MB — not saved"); return }
                    snapshot[type] = data
                }
            }
            if !snapshot.isEmpty { snapshots.append(snapshot) }
        }
        guard let first = snapshots.first else { return }
        let title: String
        let icon: String
        if first[.fileURL] != nil {
            title = snapshots.compactMap { $0[.fileURL].flatMap { String(data: $0, encoding: .utf8) }.flatMap(URL.init(string:))?.lastPathComponent }.joined(separator: ", ")
            icon = "doc"
        } else if first[.png] != nil || first[.tiff] != nil { title = L("Изображение", "Image"); icon = "photo" }
        else {
            title = String(data: first[.string] ?? first[.URL] ?? Data(), encoding: .utf8) ?? L("Текст", "Text")
            icon = first[.URL] != nil ? "link" : "text.alignleft"
        }
        entries.removeAll { $0.items == snapshots }
        entries.insert(ClipboardEntry(title: title, icon: icon, items: snapshots, date: now()), at: 0)
        while entries.count > 50 || entries.reduce(0, { $0 + $1.byteCount }) > 50 * 1024 * 1024 { entries.removeLast() }
        notice = ""
    }
    var canShowCurrentClipboard: Bool {
        capture()
        return blockedChange != board.changeCount && !shouldExclude()
            && !ClipboardPrivacy.isMarkedPrivate(board.pasteboardItems ?? [])
    }
    func copy(_ entry: ClipboardEntry) -> Bool {
        expire()
        guard entry.date > now().addingTimeInterval(-12 * 60 * 60) else {
            notice = L("Срок хранения записи истёк", "This entry has expired")
            return false
        }
        let urls = entry.items.compactMap { $0[.fileURL].flatMap { String(data: $0, encoding: .utf8) }.flatMap(URL.init(string:)) }
        guard urls.allSatisfy({ FileManager.default.fileExists(atPath: $0.path) }) else { notice = L("Файл перемещён или удалён", "File moved or deleted"); return false }
        let items = entry.items.map { snapshot -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in snapshot { item.setData(data, forType: type) }
            return item
        }
        board.clearContents()
        let success = board.writeObjects(items)
        lastChange = board.changeCount
        notice = success ? "" : L("Не удалось скопировать", "Could not copy")
        return success
    }
    func remove(_ entry: ClipboardEntry) { entries.removeAll { $0.id == entry.id } }
    func clear() { entries.removeAll(); notice = ""; lastChange = board.changeCount }
}

struct ClipboardHistoryView: View {
    @ObservedObject var history = ClipboardHistory.shared
    let close: () -> Void
    @State private var previewID: UUID?
    private var preview: ClipboardEntry? { history.entries.first { $0.id == previewID } }
    var body: some View {
        VStack(spacing: 5) {
            HStack {
                if preview != nil {
                    Button { previewID = nil } label: { Image(systemName: "chevron.left") }
                        .help(L("Назад к истории", "Back to history")).accessibilityLabel(L("Назад к истории", "Back to history"))
                }
                Text(preview != nil ? L("Предпросмотр", "Preview") : (history.paused ? L("Запись на паузе", "Recording paused") : L("История буфера", "Clipboard history"))).font(.system(size: 11)).foregroundColor(.gray)
                Spacer()
                Button { history.paused.toggle() } label: { Image(systemName: history.paused ? "play.fill" : "pause.fill") }
                    .help(history.paused ? L("Продолжить запись", "Resume recording") : L("Приостановить запись", "Pause recording"))
                Button { history.clear() } label: { Image(systemName: "trash") }.help(L("Очистить историю", "Clear history")).disabled(history.entries.isEmpty)
            }.buttonStyle(.plain)
            if let entry = preview {
                ClipboardPreview(entry: entry).frame(height: 92)
                HStack {
                    Button(L("Копировать", "Copy")) { if history.copy(entry) { close() } }
                    Spacer()
                    Button(L("Удалить", "Delete")) { history.remove(entry); previewID = nil }
                }.font(.system(size: 11)).buttonStyle(.plain)
            } else {
            ScrollView {
                LazyVStack(spacing: 5) {
                    ForEach(history.entries) { entry in
                        HStack(spacing: 6) {
                            Button { if history.copy(entry) { close() } } label: {
                                HStack(spacing: 8) {
                                    Image(systemName: entry.icon)
                                    Text(entry.title).lineLimit(1).frame(maxWidth: .infinity, alignment: .leading)
                                }.font(.system(size: 12)).padding(9).contentShape(Rectangle())
                            }.buttonStyle(.plain).help(L("Копировать и закрыть", "Copy and close"))
                            Button { previewID = entry.id } label: { Image(systemName: "eye").font(.system(size: 12)).padding(7) }
                                .buttonStyle(.plain).help(L("Предпросмотр", "Preview")).accessibilityLabel(L("Предпросмотр записи", "Preview entry"))
                            Button { history.remove(entry) } label: { Image(systemName: "xmark").font(.system(size: 10)).padding(8) }
                                .buttonStyle(.plain).help(L("Удалить запись", "Delete entry"))
                        }.background(Color.white.opacity(0.09)).cornerRadius(9)
                    }
                    if history.entries.isEmpty {
                        Text(L("Скопируй текст, изображение или файл — он появится здесь.", "Copy text, an image or a file — it will appear here."))
                            .font(.caption).foregroundColor(.gray).multilineTextAlignment(.center).padding(.top, 24)
                    }
                }
            }.frame(height: 112)
            }
            Text(history.notice.isEmpty ? L("До 50 записей · 12 ч · до выхода из приложения", "Up to 50 items · 12 hr · until you quit") : history.notice)
                .font(.system(size: 10)).foregroundColor(.gray).lineLimit(2)
        }
    }
}


private struct ClipboardPreview: View {
    let entry: ClipboardEntry
    @State private var image: NSImage?
    var body: some View {
        Group {
            if !entry.fileURLs.isEmpty {
                ScrollView {
                    VStack(alignment: .leading, spacing: 8) {
                        ForEach(Array(entry.fileURLs.enumerated()), id: \.offset) { _, url in
                            VStack(alignment: .leading, spacing: 2) {
                                Label(url.lastPathComponent, systemImage: "doc")
                                Text(url.path).font(.system(size: 10)).foregroundColor(.gray).textSelection(.enabled)
                                if !FileManager.default.fileExists(atPath: url.path) {
                                    Text(L("Файл перемещён или удалён", "File moved or deleted")).foregroundColor(.orange)
                                }
                            }.frame(maxWidth: .infinity, alignment: .leading)
                        }
                    }.padding(8)
                }
            } else if entry.items.first?[.png] != nil || entry.items.first?[.tiff] != nil {
                if let image = image {
                    Image(nsImage: image).resizable().scaledToFit().padding(4)
                        .accessibilityLabel(L("Предпросмотр скопированного изображения", "Copied image preview"))
                } else {
                    Text(L("Не удалось показать изображение", "Could not display the image")).foregroundColor(.gray)
                }
            } else {
                ScrollView {
                    Text(entry.previewText).textSelection(.enabled)
                        .frame(maxWidth: .infinity, alignment: .leading).padding(8)
                }
            }
        }.font(.system(size: 12))
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .background(Color.white.opacity(0.07)).cornerRadius(9)
            .onAppear { image = entry.previewImage() }
            .onChange(of: entry.id) { _ in image = entry.previewImage() }
    }
}
